function pi(
	key: string,
	label: string,
	description: string,
	value: ValueSchema,
	defaultValue: Json,
	extra: Partial<Entry> = {},
): Entry {
	return {
		id: `pi:/${key}`,
		path: key.split("/"),
		group: "pi",
		category: "General",
		label,
		description,
		value,
		owner: "Pi",
		ownerState: "available",
		kind: "setting",
		scopes: ["global", "project"],
		schema: "fixture-pi",
		saved: { global: { present: false }, project: { present: false } },
		default: { value: defaultValue },
		resolved: { source: "default", value: defaultValue },
		apply: { timing: "pi", text: "Pi reads this setting at startup or reload." },
		diagnostics: [],
		...extra,
	};
}
function harness(
	owner: string,
	key: string,
	label: string,
	description: string,
	value: ValueSchema,
	saved: Json,
	extra: Partial<Entry> = {},
): Entry {
	return {
		id: `harness:/${owner}/${key}`,
		path: [owner, key],
		group: "harness",
		category: owner,
		label,
		description,
		value,
		owner,
		ownerState: "available",
		kind: "setting",
		scopes: ["machine"],
		schema: `fixture-${owner}`,
		saved: { machine: { present: true, value: saved } },
		resolved: { source: "machine", value: saved },
		apply: { timing: "use", text: "The owner reads this setting at next use." },
		diagnostics: [],
		...extra,
	};
}

